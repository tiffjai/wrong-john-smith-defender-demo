"""End-to-end pipeline: candidate pairs -> name-only | Splink | Splink + guard.

The SAME candidate pairs are scored by all three methods. The pair set is generated by the
Python candidate generator below and cross-checked against the pairs Splink's blocking rules
produce; any difference raises an error.

No evaluation labels are read here.
"""
from __future__ import annotations

import itertools
from pathlib import Path

from . import baseline, guard, splink_model
from .config import load_frozen
from .data import by_case, load_alias_table, load_records
from .paths import ALIAS_PATH, FROZEN_CONFIG_PATH, RECORDS_PATH

METHODS = ("name_only", "splink", "splink_guard")


def _blocking_rule_hits(left: dict, right: dict, rules: list[dict]) -> list[str]:
    """Python implementation of the blocking rules (SQL twins live in the frozen config)."""
    hits = []
    ld, rd = left["derived"], right["derived"]
    same_case = left["case_id"] == right["case_id"]
    for rule in rules:
        if rule["key"] == "same_family_name":
            ok = same_case and ld["family_key"] is not None and ld["family_key"] == rd["family_key"]
        elif rule["key"] == "same_alias_group":
            ok = same_case and ld["alias_group"] is not None and ld["alias_group"] == rd["alias_group"]
        else:
            raise ValueError(f"no python twin for blocking rule {rule['key']}")
        if ok:
            hits.append(rule["key"])
    return hits


def candidate_pairs(records: list[dict], rules: list[dict]) -> list[dict]:
    pairs = []
    for l, r in itertools.combinations(sorted(records, key=lambda x: x["record_id"]), 2):
        hits = _blocking_rule_hits(l, r, rules)
        if hits:
            pairs.append({"pair_id": f"{l['record_id']}|{r['record_id']}", "case_id": l["case_id"],
                          "left": l["record_id"], "right": r["record_id"],
                          "left_tag": l["tag"], "right_tag": r["tag"],
                          "blocking_rules": hits})
    # display order: neighbouring tags first (A-B, B-C), then wider direct comparisons (A-C)
    pairs.sort(key=lambda p: (p["case_id"], ord(p["right_tag"]) - ord(p["left_tag"]), p["left_tag"]))
    return pairs


def route(decisions: list[str]) -> str:
    if "REVIEW" in decisions:
        return "ANALYST_REVIEW"
    if "LINK" in decisions:
        return "CANDIDATE_VISIBLE"
    return "NO_CANDIDATE"


def run_pipeline(records_path: Path = RECORDS_PATH, alias_path: Path = ALIAS_PATH,
                 config_path: Path = FROZEN_CONFIG_PATH, use_alias: bool = True) -> dict:
    frozen = load_frozen(config_path, records_path, alias_path)
    params = frozen["parameters"]
    alias = load_alias_table(alias_path)
    records = load_records(records_path, alias, use_alias=use_alias)
    rec_by_id = {r["record_id"]: r for r in records}

    pairs = candidate_pairs(records, params["splink"]["blocking_rules"])
    sp = splink_model.score_pairs(records, params["splink"])
    sp_keys = set(sp["pairs"])
    gen_keys = {(p["left"], p["right"]) for p in pairs}
    if sp_keys != gen_keys:
        raise RuntimeError(f"candidate pair mismatch between generator and Splink blocking: {sorted(sp_keys ^ gen_keys)}")

    for p in pairs:
        l, r = rec_by_id[p["left"]], rec_by_id[p["right"]]
        p["name_only"] = baseline.score_pair(l, r, params["name_only"])
        s = sp["pairs"][(p["left"], p["right"])]
        s["decision"] = splink_model.decide(s["match_probability"], params["splink"])
        p["splink"] = s

    cases = {}
    for case_id, recs in by_case(records).items():
        case_pairs = [p for p in pairs if p["case_id"] == case_id]
        g = guard.apply_guard({r["record_id"]: r for r in recs}, case_pairs, params["guard"])
        for p in case_pairs:
            p["guarded"] = g["pairs"][p["pair_id"]]
        cases[case_id] = {
            "case_id": case_id,
            "records": [r["record_id"] for r in recs],
            "pairs": [p["pair_id"] for p in case_pairs],
            "components": g["components"],
            "routes": {
                "name_only": route([p["name_only"]["decision"] for p in case_pairs]),
                "splink": route([p["splink"]["decision"] for p in case_pairs]),
                "splink_guard": route([p["guarded"]["decision"] for p in case_pairs]),
            },
        }
    return {
        "config": frozen,
        "splink_version": sp["splink_version"],
        "records": records,
        "records_by_id": rec_by_id,
        "alias": alias,
        "pairs": pairs,
        "pairs_by_id": {p["pair_id"]: p for p in pairs},
        "cases": cases,
    }


def decision_of(pair: dict, method: str) -> str:
    return {"name_only": pair["name_only"]["decision"], "splink": pair["splink"]["decision"],
            "splink_guard": pair["guarded"]["decision"]}[method]
